package com.nearair.vault.security

import com.nearair.vault.model.DeserializedNearTransaction
import com.nearair.vault.model.NearAction
import java.math.BigDecimal

enum class EnclavePolicyTier {
    ALLOWED,
    WARNING,
    BLOCKED
}

data class EnclavePolicyResult(
    val tier: EnclavePolicyTier,
    val score: Int, // 0 to 100
    val statusTitle: String,
    val violations: List<String>,
    val warnings: List<String>,
    val passedRules: List<String>,
    val requiresExplicitOverride: Boolean = false
)

/**
 * Hardened On-Device Hardware Enclave Policy Engine
 *
 * Runs inside the air-gapped device before any Ed25519 signature is generated by the TEE.
 * Enforces hardware spending limits, immutable blocklists, and key permission scoping.
 */
object EnclavePolicyEngine {

    // Configurable Hardware Enclave Limits
    var maxSingleTxNear: Double = 50.0
    var highValueThresholdNear: Double = 5.0

    // Immutable on-device blocklist of verified drainers, honey-pots, and malicious smart contracts
    private val hardwareBlocklist = setOf(
        "drainer.testnet", "drainer.near",
        "honeypot.testnet", "honeypot.near",
        "fake-airdrop.testnet", "fake-airdrop.near",
        "malicious-agent.testnet", "exploit.near",
        "phish-wallet.testnet", "stealer.testnet",
        "prompt-inject-drainer.testnet", "blackhat-bot.near"
    )

    /**
     * Evaluate a deserialized Borsh transaction against the air-gapped security policy
     */
    fun evaluate(
        tx: DeserializedNearTransaction,
        vaultAccountId: String,
        vaultPublicKey: String
    ): EnclavePolicyResult {
        val violations = mutableListOf<String>()
        val warnings = mutableListOf<String>()
        val passedRules = mutableListOf<String>()

        val normalizedTxKey = if (tx.publicKey.trim().startsWith("ed25519:")) tx.publicKey.trim() else "ed25519:${tx.publicKey.trim()}"
        val normalizedVaultKey = if (vaultPublicKey.trim().startsWith("ed25519:")) vaultPublicKey.trim() else "ed25519:${vaultPublicKey.trim()}"

        // ----------------------------------------------------
        // RULE 1: Hardware Signer Key & Account Verification
        // ----------------------------------------------------
        if (normalizedTxKey != normalizedVaultKey) {
            warnings.add("Transaction authorizer (${tx.publicKey.take(16)}...) differs from default local key (${vaultPublicKey.take(16)}...)")
        } else {
            passedRules.add("Hardware key ownership verified")
        }

        if (vaultAccountId.isNotBlank() && !tx.signerId.equals(vaultAccountId.trim(), ignoreCase = true)) {
            warnings.add("Signing on behalf of account: ${tx.signerId} (Local Vault: $vaultAccountId)")
        } else if (vaultAccountId.isNotBlank()) {
            passedRules.add("Signer Account ID ($vaultAccountId) verified")
        }

        // ----------------------------------------------------
        // RULE 2: Immutable Enclave Blocklist
        // ----------------------------------------------------
        val target = tx.receiverId.trim().lowercase()
        if (hardwareBlocklist.contains(target)) {
            violations.add("CRITICAL: Recipient '$target' is a verified malicious drainer/exploit address on the Enclave Blocklist")
        } else {
            passedRules.add("Recipient not in drainer blocklist")
        }

        // ----------------------------------------------------
        // RULE 3: Spending Limits & Anomaly Caps
        // ----------------------------------------------------
        val amountDouble = try {
            tx.totalNearAmount.toDouble()
        } catch (_: Exception) {
            0.0
        }

        if (amountDouble > maxSingleTxNear) {
            violations.add("Exceeded hard spending limit: ${amountDouble} NEAR > Hardware Max Cap (${maxSingleTxNear} NEAR)")
        } else if (amountDouble > highValueThresholdNear) {
            warnings.add("High-value transaction: ${amountDouble} NEAR exceeds safety review threshold (${highValueThresholdNear} NEAR)")
        } else {
            passedRules.add("Amount within normal limits (${amountDouble} NEAR)")
        }

        // ----------------------------------------------------
        // RULE 4: Key Permission Scoping & Escalation Detection
        // ----------------------------------------------------
        for (action in tx.actions) {
            if (action is NearAction.AddKey) {
                if (action.isFullAccess) {
                    warnings.add("CRITICAL ESCALATION: Adding a FULL ACCESS KEY to ${tx.signerId}. This grants total irrevocable account control!")
                } else {
                    val receiver = action.receiverId ?: "any"
                    val methods = if (action.methodNames.isEmpty()) "all" else action.methodNames.joinToString(", ")
                    passedRules.add("Scoped Function-Call key for contract: $receiver (methods: $methods)")
                }
            }
        }

        // Tier Determination
        val tier = when {
            violations.isNotEmpty() -> EnclavePolicyTier.BLOCKED
            warnings.isNotEmpty() -> EnclavePolicyTier.WARNING
            else -> EnclavePolicyTier.ALLOWED
        }

        val score = when (tier) {
            EnclavePolicyTier.ALLOWED -> 100
            EnclavePolicyTier.WARNING -> (70 - warnings.size * 15).coerceAtLeast(35)
            EnclavePolicyTier.BLOCKED -> 0
        }

        val title = when (tier) {
            EnclavePolicyTier.ALLOWED -> "Policy Verified: Safe to Sign"
            EnclavePolicyTier.WARNING -> "Security Warning: Human Review Required"
            EnclavePolicyTier.BLOCKED -> "SIGNING BLOCKED BY ENCLAVE POLICY"
        }

        return EnclavePolicyResult(
            tier = tier,
            score = score,
            statusTitle = title,
            violations = violations,
            warnings = warnings,
            passedRules = passedRules,
            requiresExplicitOverride = tier == EnclavePolicyTier.WARNING
        )
    }
}
